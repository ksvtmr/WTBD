def h(t,size=18,color=DK):
    p=d.add_paragraph(); r=p.add_run(t); r.bold=True; r.font.size=Pt(size); r.font.color.rgb=color; return p
def para(t,opt=None,bold_first=None):
    p=d.add_paragraph()
    r=p.add_run(t); r.font.size=Pt(13)
    if opt:
        r2=p.add_run(' ['+opt+']'); r2.font.size=Pt(11); r2.font.color.rgb=MU; r2.italic=True
    p.paragraph_format.space_after=Pt(6); return p
def block(time,slide,who,text,cut=None):
    p=d.add_paragraph(); r=p.add_run(f'{time}  ·  {slide}  ·  {who}'); r.bold=True; r.font.color.rgb=AC; r.font.size=Pt(11)
    p.paragraph_format.space_before=Pt(10); p.paragraph_format.space_after=Pt(2)
    for t in text: para(t)
    if cut:
        p=d.add_paragraph(); r=p.add_run('Если отстаём — пропустить: '+cut); r.italic=True; r.font.size=Pt(10.5); r.font.color.rgb=MU

